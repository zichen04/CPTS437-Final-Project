import os
import csv
import random
from collections import deque

import gymnasium as gym
import panda_gym
import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim

from stable_baselines3 import PPO
from stable_baselines3.common.callbacks import EvalCallback


# ============================================================
# 1. Experiment configuration
# ============================================================

ENV_ID = "PandaReach-v3"
TOTAL_TIMESTEPS = 100_000
EVAL_FREQ = 10_000
N_EVAL_EPISODES = 10

SEED = 42
CURIOSITY_BETA = 0.1
BATCH_SIZE = 64

OUTPUT_DIR = "results"
os.makedirs(OUTPUT_DIR, exist_ok=True)

torch.manual_seed(SEED)
np.random.seed(SEED)
random.seed(SEED)


# ============================================================
# 2. Learned dynamics model
#    Supervised prediction of the next observation change
# ============================================================

class DynamicsModel(nn.Module):
    def __init__(self, state_dim, action_dim):
        super().__init__()

        self.network = nn.Sequential(
            nn.Linear(state_dim + action_dim, 128),
            nn.ReLU(),
            nn.Linear(128, 128),
            nn.ReLU(),
            nn.Linear(128, state_dim),
        )

    def forward(self, state, action):
        x = torch.cat([state, action], dim=1)
        return self.network(x)


# ============================================================
# 3. Curiosity wrapper
#    Collect experience online and reward prediction error
# ============================================================

class CuriosityWrapper(gym.Wrapper):
    def __init__(
        self,
        env,
        beta=CURIOSITY_BETA,
        batch_size=BATCH_SIZE,
        buffer_size=50_000,
    ):
        super().__init__(env)

        self.beta = beta
        self.batch_size = batch_size

        state_dim = env.observation_space["observation"].shape[0]
        action_dim = env.action_space.shape[0]

        self.dynamics = DynamicsModel(state_dim, action_dim)
        self.optimizer = optim.Adam(
            self.dynamics.parameters(), lr=1e-3
        )
        self.loss_fn = nn.MSELoss()

        # No static dataset: transitions are collected during training.
        self.buffer = deque(maxlen=buffer_size)
        self.step_count = 0

    def _state(self, obs):
        return np.asarray(
            obs["observation"], dtype=np.float32
        )

    def step(self, action):
        obs, reward, terminated, truncated, info = (
            self.env.step(action)
        )

        # The model predicts the change in observation.
        state = self._state(self._last_obs)
        next_state = self._state(obs)
        action = np.asarray(action, dtype=np.float32)

        state_t = torch.as_tensor(state).unsqueeze(0)
        action_t = torch.as_tensor(action).unsqueeze(0)

        # Calculate prediction error BEFORE training on this transition.
        with torch.no_grad():
            predicted_delta = self.dynamics(state_t, action_t)
            actual_delta = torch.as_tensor(
                next_state - state
            ).unsqueeze(0)

            prediction_error = torch.mean(
                (predicted_delta - actual_delta) ** 2
            ).item()

        # Bound the intrinsic reward to reduce reward-scale problems.
        intrinsic_reward = min(prediction_error, 1.0)

        # Store experience generated by the environment.
        self.buffer.append(
            (state, action, next_state - state)
        )

        self.step_count += 1

        # Online supervised learning.
        # Train every 4 steps once enough data is available.
        if (
            len(self.buffer) >= self.batch_size
            and self.step_count % 4 == 0
        ):
            self._train_dynamics()

        self._last_obs = obs

        combined_reward = float(reward) + (
            self.beta * intrinsic_reward
        )

        info = dict(info)
        info["extrinsic_reward"] = float(reward)
        info["intrinsic_reward"] = float(intrinsic_reward)

        return (
            obs,
            combined_reward,
            terminated,
            truncated,
            info,
        )

    def _train_dynamics(self):
        batch = random.sample(
            self.buffer, self.batch_size
        )

        states, actions, deltas = zip(*batch)

        states_t = torch.as_tensor(
            np.asarray(states), dtype=torch.float32
        )
        actions_t = torch.as_tensor(
            np.asarray(actions), dtype=torch.float32
        )
        deltas_t = torch.as_tensor(
            np.asarray(deltas), dtype=torch.float32
        )

        predictions = self.dynamics(states_t, actions_t)
        loss = self.loss_fn(predictions, deltas_t)

        self.optimizer.zero_grad()
        loss.backward()
        self.optimizer.step()

    def reset(self, **kwargs):
        obs, info = self.env.reset(**kwargs)
        self._last_obs = obs
        return obs, info


# ============================================================
# 4. Create training environments
# ============================================================

def make_training_env(use_curiosity):
    env = gym.make(ENV_ID)

    if use_curiosity:
        env = CuriosityWrapper(env)

    return env


# ============================================================
# 5. Evaluate on the ORIGINAL task reward
# ============================================================

def evaluate_agent(model, env, episodes=10):
    episode_returns = []
    successes = []

    for episode in range(episodes):
        obs, info = env.reset(seed=SEED + 1000 + episode)
        total_reward = 0.0
        episode_success = False

        while True:
            action, _ = model.predict(
                obs, deterministic=True
            )

            obs, reward, terminated, truncated, info = (
                env.step(action)
            )

            # Use the task reward, not the curiosity reward.
            total_reward += float(
                info.get("extrinsic_reward", reward)
            )

            if "is_success" in info:
                episode_success = bool(
                    np.asarray(info["is_success"]).item()
                )

            if terminated or truncated:
                break

        episode_returns.append(total_reward)
        successes.append(float(episode_success))

    return {
        "mean_return": float(np.mean(episode_returns)),
        "std_return": float(np.std(episode_returns)),
        "success_rate": float(np.mean(successes)),
    }


# ============================================================
# 6. Train and compare baseline vs curiosity-driven PPO
# ============================================================

def run_experiment(name, use_curiosity):
    print(f"\nStarting experiment: {name}")

    train_env = make_training_env(use_curiosity)
    eval_env = gym.make(ENV_ID)

    try:
        callback = EvalCallback(
            eval_env,
            best_model_save_path=os.path.join(
                OUTPUT_DIR, name, "best"
            ),
            log_path=os.path.join(OUTPUT_DIR, name),
            eval_freq=EVAL_FREQ,
            n_eval_episodes=N_EVAL_EPISODES,
            deterministic=True,
            verbose=1,
        )

        model = PPO(
            "MultiInputPolicy",
            train_env,
            learning_rate=3e-4,
            n_steps=2048,
            batch_size=64,
            gamma=0.99,
            seed=SEED,
            verbose=1,
        )

        model.learn(
            total_timesteps=TOTAL_TIMESTEPS,
            callback=callback,
        )

        model_path = os.path.join(
            OUTPUT_DIR, f"{name}_final"
        )
        model.save(model_path)

        metrics = evaluate_agent(
            model, eval_env, episodes=N_EVAL_EPISODES
        )

        print(f"\nResults: {name}")
        print(f"Mean task return: {metrics['mean_return']:.3f}")
        print(f"Return std:       {metrics['std_return']:.3f}")
        print(f"Success rate:     {metrics['success_rate']:.1%}")

        return {
            "method": name,
            "timesteps": TOTAL_TIMESTEPS,
            **metrics,
        }

    finally:
        train_env.close()
        eval_env.close()


# ============================================================
# 7. Run both experiments and save the comparison
# ============================================================

if __name__ == "__main__":
    results = []

    results.append(
        run_experiment(
            name="baseline_ppo",
            use_curiosity=False,
        )
    )

    results.append(
        run_experiment(
            name="curiosity_ppo",
            use_curiosity=True,
        )
    )

    csv_path = os.path.join(
        OUTPUT_DIR, "comparison.csv"
    )

    with open(csv_path, "w", newline="") as file:
        writer = csv.DictWriter(
            file, fieldnames=results[0].keys()
        )
        writer.writeheader()
        writer.writerows(results)

    print("\nFinal comparison")
    for result in results:
        print(result)

    print(f"\nResults saved to {csv_path}")
    
